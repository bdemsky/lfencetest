#!/usr/bin/env python3
"""Generate unrolled.c: fully unrolled "clflushopt L; FENCE; load L" sequences.

Each generated function runs one triple per test line (LINES of them),
back to back with nothing in between, so later flushes can overlap with
earlier ones. Compare gpu_stale.c, which separates trials with an mfence.

For every (line order, fence) pair it emits two versions:

  u_<order>_<fence>_st(base, out)
      out[i] = value loaded at step i. Each step is
          clflushopt L; FENCE; mov L -> eax; mov eax -> out[i]
      so every triple also does a store (to out[], which is cache resident).

  u_<order>_<fence>_reg(base, newv) -> number of stale loads
      No stores at all: each step is
          clflushopt L; FENCE; mov L -> eax; cmp newv, eax; adc $0, count
      The cmp sets the carry flag when eax < newv (unsigned). Since the
      driver always picks OLD < NEW, adc counts exactly the stale loads.

Line orders: "seq" visits lines 0..LINES-1; "rand" uses a fixed shuffle.
Every line offset is baked into the code as an immediate displacement off
the base register, so there's no address arithmetic and no loop.

The file also contains uvariants[], a table the driver (unrolled_test.c)
iterates over, including each variant's line order so stale positions can
be mapped back to lines.
"""
import random

LINES, LINE = 2048, 64  # must match gpu_nc.h
ORDERS = {"seq": list(range(LINES))}
_rnd = list(range(LINES))
random.Random(1).shuffle(_rnd)
ORDERS["rand"] = _rnd
FENCES = {  # name -> instructions placed between the clflushopt and the load
    "none": "",
    "lfence": "lfence\\n\\t",
    "sflf": "sfence\\n\\tlfence\\n\\t",
    "mfence": "mfence\\n\\t",
}

out = ["// Generated by gen_unrolled.py -- do not edit.",
       '#include "unrolled.h"', ""]
for oname, order in ORDERS.items():
    out.append(f"static const uint16_t order_{oname}[{LINES}] = {{" +
               ",".join(map(str, order)) + "};")
out.append("")

table = []
for oname, order in ORDERS.items():
    for fname, fence in FENCES.items():
        st, reg = f"u_{oname}_{fname}_st", f"u_{oname}_{fname}_reg"
        body = "".join(
            f'    "clflushopt {o * LINE}(%0)\\n\\t{fence}'
            f'mov {o * LINE}(%0), %%eax\\n\\tmov %%eax, {i * 4}(%1)\\n\\t"\n'
            for i, o in enumerate(order))
        out.append(f"static void {st}(volatile uint32_t *b, uint32_t *out) {{\n"
                   f"  asm volatile(\n{body}"
                   f'    :: "r"(b), "r"(out) : "rax", "memory");\n}}\n')
        body = "".join(
            f'    "clflushopt {o * LINE}(%1)\\n\\t{fence}'
            f'mov {o * LINE}(%1), %%eax\\n\\tcmp %2, %%eax\\n\\tadc $0, %0\\n\\t"\n'
            for o in order)
        out.append(f"static long {reg}(volatile uint32_t *b, uint32_t newv) {{\n"
                   f"  long n = 0;\n  asm volatile(\n{body}"
                   f'    : "+r"(n) : "r"(b), "r"(newv) : "rax", "cc", "memory");\n'
                   f"  return n;\n}}\n")
        table.append(f'  {{"{oname:<4} {fname}", {int(fname != "none")}, '
                     f"order_{oname}, {st}, {reg}}},")

out.append("const struct uvariant uvariants[] = {")
out += table
out.append("};")
out.append(f"const int n_uvariants = {len(table)};")
open("unrolled.c", "w").write("\n".join(out) + "\n")
